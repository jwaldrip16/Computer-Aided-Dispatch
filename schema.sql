ALTER TABLE users ADD COLUMN IF NOT EXISTS unit_status TEXT;
ALTER TABLE users ADD COLUMN IF NOT EXISTS lat DOUBLE PRECISION;
ALTER TABLE users ADD COLUMN IF NOT EXISTS lng DOUBLE PRECISION;
ALTER TABLE users ADD COLUMN IF NOT EXISTS loc_updated TIMESTAMPTZ;
ALTER TABLE calls ADD COLUMN IF NOT EXISTS notified_at TIMESTAMPTZ;

ALTER TABLE calls ADD COLUMN IF NOT EXISTS lat DOUBLE PRECISION;
ALTER TABLE calls ADD COLUMN IF NOT EXISTS response_channel TEXT;
CREATE TABLE IF NOT EXISTS call_pages (
    id SERIAL PRIMARY KEY,
    call_id INTEGER NOT NULL REFERENCES calls(id) ON DELETE CASCADE,
    units TEXT,
    paged_at TIMESTAMPTZ DEFAULT now(),
    page_text TEXT,
    audio BYTEA
);
ALTER TABLE calls ADD COLUMN IF NOT EXISTS lng DOUBLE PRECISION;

ALTER TABLE calls ADD COLUMN IF NOT EXISTS addr_formatted TEXT;

CREATE TABLE IF NOT EXISTS unit_call_status (
  id SERIAL PRIMARY KEY,
  call_id INT NOT NULL REFERENCES calls(id) ON DELETE CASCADE,
  username TEXT NOT NULL,
  status TEXT NOT NULL,
  reason TEXT,
  lat DOUBLE PRECISION,
  lng DOUBLE PRECISION,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_unit_call_status_call ON unit_call_status (call_id);
